#!/usr/bin/python3
"""Liberty timing models for the cells FreePDK45 does not have.

forte_top instantiates SRAM macros (rf_sp_*) and pad cells (io_in, io_out,
io_tri) that only exist in the 65 nm kit.  Left unresolved, every path through
a cache or a pad is simply not timed.  This writes one .lib giving each of them
interface timing only -- clock-to-Q and setup/hold for the memories, a fixed
delay for the pads -- so those paths are timed against the budgets in tech.cfg.

The numbers in tech.cfg are 65 nm nanoseconds.  They are divided by the scale
factor K here, because the synthesis they are linked into runs in the
calibration library's time base (see tech.tcl).

usage: gen_blackbox_libs.py <tech.cfg> <fo4_of_calibration_library_ps> <out.lib>
"""

import os
import sys

# name: (address bits, data bits, chip-enable pin, write-enable pin, bit-write pin or None)
SRAMS = {
    "rf_sp_16_46":  (4, 48,  "CEN", "WEN", None),
    "rf_sp_16_128": (4, 128, "CEN", "WEN", None),
    "rf_sp_32_45":  (5, 48,  "CEN", "WEN", None),
    "rf_sp_32_128": (5, 128, "CEN", "WEN", None),
    "rf_sp_64_44":  (6, 44,  "CEN", "WEN", None),
    "rf_sp_64_46":  (6, 46,  "CEN", "WEN", None),
    "rf_sp_64_128": (6, 128, "CEN", "WEN", None),
    "rf_sp_64_53":  (6, 53,  "CEN", "WEN", None),   # cache tag + SECDED check bits
    "rf_sp_64_137": (6, 137, "CEN", "WEN", None),   # cache line + SECDED check bits
    "TS1N28HPCPSVTB64X44M4SW": (6, 44, "CEB", "WEB", "BWEB"),
}


def read_cfg(path):
    cfg = {}
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if len(line) == 2:
                cfg[line[0]] = float(os.environ.get(line[0], line[1]))
    return cfg


def scalar(group, value):
    return f'{group} (scalar) {{ values ("{value:.4f}"); }}'


def constraint(related, kind, value):
    return (f'timing () {{ related_pin : "{related}"; timing_type : {kind}; '
            f'{scalar("rise_constraint", value)} {scalar("fall_constraint", value)} }}')


def delay(related, value, extra=""):
    return (f'timing () {{ related_pin : "{related}"; {extra}'
            f'{scalar("cell_rise", value)} {scalar("cell_fall", value)} '
            f'{scalar("rise_transition", 0.05)} {scalar("fall_transition", 0.05)} }}')


def sram_cell(name, abits, dbits, ce, we, bwe, tacc, tsu, th):
    def checks():
        return f'{constraint("CLK", "setup_rising", tsu)} {constraint("CLK", "hold_rising", th)}'

    def in_pin(pin):
        return f'    pin ({pin}) {{ direction : input; capacitance : 2.0; {checks()} }}\n'

    def in_bus(bus, bus_type):
        return (f'    bus ({bus}) {{ bus_type : {bus_type}; direction : input; capacitance : 2.0; '
                f'{checks()} }}\n')

    out = f'  cell ({name}) {{\n'
    out += '    area : 0; dont_touch : true; dont_use : true; interface_timing : true;\n'
    out += '    pin (CLK) { direction : input; clock : true; capacitance : 5.0; }\n'
    out += in_pin(ce) + in_pin(we)
    out += in_bus("A", f"bus{abits}") + in_bus("D", f"bus{dbits}")
    if bwe:
        out += in_bus(bwe, f"bus{dbits}")
    out += (f'    bus (Q) {{ bus_type : bus{dbits}; direction : output; '
            f'{delay("CLK", tacc, "timing_type : rising_edge; ")} }}\n')
    out += '  }\n'
    return out


def pad_cells(t_in, t_out):
    buf = 'timing_sense : positive_unate; '
    return f'''  cell (io_in) {{
    area : 0; pad_cell : true; dont_touch : true; dont_use : true;
    pin (chipout) {{ direction : input; is_pad : true; capacitance : 5.0; }}
    pin (chipin) {{ direction : output; function : "chipout"; {delay("chipout", t_in, buf)} }}
  }}
  cell (io_out) {{
    area : 0; pad_cell : true; dont_touch : true; dont_use : true;
    pin (chipin) {{ direction : input; capacitance : 5.0; }}
    pin (chipout) {{ direction : output; is_pad : true; function : "chipin"; {delay("chipin", t_out, buf)} }}
  }}
  cell (io_tri) {{
    area : 0; pad_cell : true; dont_touch : true; dont_use : true;
    pin (o) {{ direction : input; capacitance : 5.0; }}
    pin (t) {{ direction : input; capacitance : 5.0; }}
    pin (chipout) {{
      direction : inout; is_pad : true; capacitance : 5.0; function : "o"; three_state : "t";
      {delay("o", t_out, buf)}
      {delay("t", t_out, "timing_type : three_state_enable; timing_sense : negative_unate; ")}
      {delay("t", t_out, "timing_type : three_state_disable; timing_sense : positive_unate; ")}
    }}
    pin (i) {{ direction : output; function : "chipout"; {delay("chipout", t_in, buf)} }}
  }}
'''


def main():
    cfg_path, fo4_cal_ps, out_path = sys.argv[1], float(sys.argv[2]), sys.argv[3]
    cfg = read_cfg(cfg_path)
    k = cfg["TARGET_FO4_PS"] / fo4_cal_ps

    def cal(ns65):
        return ns65 / k

    widths = sorted({s[0] for s in SRAMS.values()} | {s[1] for s in SRAMS.values()})
    lib = f'''/* Generated by synth/timing/gen_blackbox_libs.py -- do not edit.
   Times are in the calibration library's time base: 65 nm ns / K, K = {k:.4f}. */
library (forte_blackbox) {{
  technology (cmos);
  delay_model : table_lookup;
  time_unit : "1ns";
  voltage_unit : "1V";
  current_unit : "1mA";
  pulling_resistance_unit : "1kohm";
  leakage_power_unit : "1nW";
  capacitive_load_unit (1,ff);
  nom_process : 1.0;
  nom_temperature : 25.0;
  nom_voltage : 1.1;
  slew_lower_threshold_pct_fall : 30.0;
  slew_lower_threshold_pct_rise : 30.0;
  slew_upper_threshold_pct_fall : 70.0;
  slew_upper_threshold_pct_rise : 70.0;
  input_threshold_pct_fall : 50.0;
  input_threshold_pct_rise : 50.0;
  output_threshold_pct_fall : 50.0;
  output_threshold_pct_rise : 50.0;
'''
    for w in widths:
        lib += (f'  type (bus{w}) {{ base_type : array; data_type : bit; bit_width : {w}; '
                f'bit_from : {w - 1}; bit_to : 0; downto : true; }}\n')
    for name, (abits, dbits, ce, we, bwe) in SRAMS.items():
        lib += sram_cell(name, abits, dbits, ce, we, bwe,
                         cal(cfg["SRAM_TACC_NS"]), cal(cfg["SRAM_TSU_NS"]), cal(cfg["SRAM_TH_NS"]))
    lib += pad_cells(cal(cfg["PAD_IN_NS"]), cal(cfg["PAD_OUT_NS"]))
    lib += '}\n'

    with open(out_path, "w") as f:
        f.write(lib)


if __name__ == "__main__":
    main()
