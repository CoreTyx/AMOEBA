#!/usr/bin/env python3
"""
gen_test_cfg.py -- derive testcode/stress/lib/amoeba_cfg.h from pkg/config.vh.

The stress suite sizes itself from the configuration the chip actually ships
(TLB entries, cache geometry, PMP count, memory map, PLIC source IDs, which
extensions exist) instead of hard-coding numbers that silently go stale when
the config changes.  Every `localparam NAME = <literal>;` in pkg/config.vh whose
value is a plain Verilog literal becomes `#define AMOEBA_NAME <value>`, and a few
derived quantities are added at the end.

    python3 bin/gen_test_cfg.py            # rewrite the header
    python3 bin/gen_test_cfg.py --check    # exit 1 if the header is stale (CI)

Only the first definition of a name is used: pkg/config.vh guards USE_SRAM
with `ifdef SYNTHESIS, and the simulation value is not needed by any test.
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(REPO, "pkg", "config.vh")
SHARED = os.path.join(REPO, "pkg", "config-shared.vh")
OUT = os.path.join(REPO, "testcode", "stress", "lib", "amoeba_cfg.h")

LP = re.compile(r"^\s*localparam\s+(?:logic\s*(?:\[[^\]]*\]\s*)?)?(\w+)\s*=\s*([^;]+);")


def parse_literal(text):
    """Return the integer value of a plain Verilog literal, or None."""
    v = text.strip().replace("_", "")
    m = re.fullmatch(r"(\d+)?'([bdhBDH])([0-9a-fA-F]+)", v)
    if m:
        base = {"b": 2, "d": 10, "h": 16}[m.group(2).lower()]
        return int(m.group(3), base)
    if re.fullmatch(r"\d+", v):
        return int(v)
    return None


XLEN_TERNARY = re.compile(r"\(\s*XLEN\s*==\s*32\s*\?\s*([^:]+?)\s*:\s*([^)]+?)\s*\)$")


def collect(path, xlen=64):
    """Plain literals, plus the `(XLEN==32 ? a : b)` form config-shared.vh uses."""
    vals = {}
    if not os.path.isfile(path):
        return vals
    with open(path) as f:
        for line in f:
            line = line.split("//", 1)[0]
            m = LP.match(line)
            if not m:
                continue
            name, rhs = m.group(1), m.group(2)
            if name in vals:
                continue
            val = parse_literal(rhs)
            if val is None:
                t = XLEN_TERNARY.match(rhs.strip())
                if t:
                    val = parse_literal(t.group(1) if xlen == 32 else t.group(2))
            if val is not None:
                vals[name] = val
    return vals


def render(vals):
    out = []
    w = out.append
    w("/* GENERATED by bin/gen_test_cfg.py from pkg/config.vh -- do not edit.")
    w(" * Regenerate with:  python3 bin/gen_test_cfg.py")
    w(" * CI fails if this file is stale (python3 bin/gen_test_cfg.py --check). */")
    w("#ifndef AMOEBA_CFG_H")
    w("#define AMOEBA_CFG_H")
    w("")
    for name in sorted(vals):
        v = vals[name]
        w(f"#define AMOEBA_{name:<32} 0x{v:x}ULL" if v > 0xffff else f"#define AMOEBA_{name:<32} {v}")
    w("")
    w("/* ---- derived ---- */")

    def g(n, d=0):
        return vals.get(n, d)

    dline = g("DCACHE_LINELENINBITS", 128) // 8
    iline = g("ICACHE_LINELENINBITS", 128) // 8
    w(f"#define AMOEBA_DCACHE_LINE_BYTES          {dline}")
    w(f"#define AMOEBA_ICACHE_LINE_BYTES          {iline}")
    w(f"#define AMOEBA_DCACHE_SETS                {g('DCACHE_WAYSIZEINBYTES', 1024) // dline}")
    w(f"#define AMOEBA_ICACHE_SETS                {g('ICACHE_WAYSIZEINBYTES', 1024) // iline}")
    w(f"#define AMOEBA_DCACHE_BYTES               {g('DCACHE_WAYSIZEINBYTES', 1024) * g('DCACHE_NUMWAYS', 4)}")
    w(f"#define AMOEBA_ICACHE_BYTES               {g('ICACHE_WAYSIZEINBYTES', 1024) * g('ICACHE_NUMWAYS', 2)}")
    # MISA as the core reports it (pkg/config-shared.vh builds it from the same flags)
    misa = 0
    for letter, flag in (("A", "ZAAMO_SUPPORTED"), ("C", "ZCA_SUPPORTED"), ("D", "D_SUPPORTED"),
                         ("F", "F_SUPPORTED"), ("M", "M_SUPPORTED"), ("S", "S_SUPPORTED"),
                         ("U", "U_SUPPORTED"), ("Q", "Q_SUPPORTED")):
        if g(flag):
            misa |= 1 << (ord(letter) - ord("A"))
    misa |= 1 << (ord("E" if g("E_SUPPORTED") else "I") - ord("A"))
    w(f"#define AMOEBA_MISA_EXT_BITS              0x{misa:x}ULL")
    w(f"#define AMOEBA_HAS_COUNTERS               {1 if (g('ZICNTR_SUPPORTED') or g('ZIHPM_SUPPORTED')) else 0}")
    w(f"#define AMOEBA_HAS_FPU                    {1 if (g('F_SUPPORTED') or g('D_SUPPORTED')) else 0}")
    w(f"#define AMOEBA_HW_MISALIGNED              {g('ZICCLSM_SUPPORTED')}")
    w(f"#define AMOEBA_HW_AD_UPDATE               {g('SVADU_SUPPORTED')}")
    w(f"#define AMOEBA_EXT_MEM_END                0x{g('EXT_MEM_BASE', 0x80000000) + g('EXT_MEM_RANGE', 0x0fffffff) + 1:x}ULL")
    w("")
    w("#endif /* AMOEBA_CFG_H */")
    return "\n".join(out) + "\n"


def main():
    vals = collect(SHARED)
    vals.update(collect(CONFIG))  # config.vh wins
    text = render(vals)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.isfile(OUT) else ""
        if cur != text:
            sys.stderr.write("ERROR: testcode/stress/lib/amoeba_cfg.h is stale -- run python3 bin/gen_test_cfg.py\n")
            return 1
        print("amoeba_cfg.h is up to date.")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, REPO)} ({len(vals)} parameters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
